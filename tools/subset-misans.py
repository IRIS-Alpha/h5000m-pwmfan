#!/usr/bin/env python3
"""Rebuild the MiSans subset shipped with this plugin.

MiSans is licensed under the Apache License 2.0 and published as the npm
package ``misans`` (https://www.npmjs.com/package/misans). The upstream
release ships the family split into dozens of ``unicode-range`` chunks; we
keep only the glyphs this user interface actually renders, so the payload
stays small enough for a router.

Steps:

1. collect every character used by the plugin (po catalogues + view code),
2. for each chunk of ``MiSans-Regular`` and ``MiSans-Demibold``, subset it
   to the intersection of its ``unicode-range`` and that character set,
3. write the woff2 files and the ``@font-face`` stylesheet.

Usage::

    python3 tools/subset-misans.py --cache /tmp/misans

Requires ``fonttools`` with brotli support (``pip install fonttools brotli``).
"""

from __future__ import annotations

import argparse
import io
import os
import re
import subprocess
import sys
import urllib.request

VERSION = "5.0.0"
BASE = "https://cdn.jsdelivr.net/npm/misans@%s/lib/Normal/" % VERSION
WEIGHTS = ("Regular", "Demibold")
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(REPO, "htdocs", "luci-static", "resources", "view", "fonts")
CSS_PATH = os.path.join(REPO, "htdocs", "luci-static", "resources", "view", "h5000m-pwmfan-font.css")


def collect_chars() -> str:
    """Return every character the plugin can show, sorted and unique."""
    chars = set(chr(c) for c in range(0x20, 0x7F))
    for root, _dirs, files in os.walk(os.path.join(REPO, "po")):
        for name in files:
            if name.endswith(".po"):
                text = io.open(os.path.join(root, name), encoding="utf-8").read()
                for line in text.splitlines():
                    if line.startswith(("msgid ", "msgstr ")):
                        chars.update(re.findall(r'"([^"]*)"', line)[0] or "")
    # Chinese punctuation and unit symbols used outside the catalogues.
    chars.update("°%·—…℃×")
    return "".join(sorted(chars))


def fetch(url: str, cache: str) -> str:
    """Download url into cache (once) and return the local path."""
    name = url.rsplit("/", 1)[-1]
    path = os.path.join(cache, name)
    if not os.path.exists(path):
        sys.stderr.write("fetch %s\n" % name)
        urllib.request.urlretrieve(url, path)
    return path


def parse_ranges(spec: str) -> list[tuple[int, int]]:
    ranges = []
    for part in spec.split(","):
        part = part.strip().replace("U+", "")
        if not part:
            continue
        if "-" in part:
            low, high = part.split("-")
            ranges.append((int(low, 16), int(high, 16)))
        else:
            value = int(part, 16)
            ranges.append((value, value))
    return ranges


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", default=os.path.join("/tmp", "misans"), help="chunk download cache")
    args = parser.parse_args()
    os.makedirs(args.cache, exist_ok=True)
    os.makedirs(OUT_DIR, exist_ok=True)

    chars = collect_chars()
    faces = []
    for weight in WEIGHTS:
        css = io.open(fetch(BASE + "MiSans-%s.min.css" % weight, args.cache), encoding="utf-8").read()
        for block in re.findall(r"@font-face\{[^}]*\}", css):
            url = re.search(r"url\('([^']+)'\)", block).group(1)
            name = url.rsplit("/", 1)[-1]
            number = re.search(r"font-weight:(\d+)", block).group(1)
            spec = re.search(r"unicode-range:([^;}]*)", block).group(1)
            ranges = parse_ranges(spec)
            wanted = [c for c in chars if any(low <= ord(c) <= high for low, high in ranges)]
            if not wanted:
                continue
            source = fetch(BASE + name, args.cache)
            stem = name.rsplit(".", 3)[-3]
            target = "%s-%s.woff2" % (weight.lower(), stem)
            subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "fontTools.subset",
                    source,
                    "--unicodes=" + ",".join("U+%04X" % ord(c) for c in wanted),
                    "--flavor=woff2",
                    "--layout-features=*",
                    "--no-hinting",
                    "--desubroutinize",
                    "--output-file=" + os.path.join(OUT_DIR, target),
                ],
                check=True,
            )
            faces.append((number, target, spec.strip()))
            print("%s %s %d glyphs" % (weight, target, len(wanted)))

    lines = ["/* MiSans (subset, Apache-2.0) - generated by tools/subset-misans.py from misans@%s; */" % VERSION]
    lines.append("/* glyphs are limited to the characters this plugin renders. */")
    for number, target, spec in faces:
        lines.append(
            "@font-face{font-family:MiSans;font-style:normal;font-weight:%s;font-display:swap;"
            "src:url('fonts/%s') format('woff2');unicode-range:%s}" % (number, target, spec)
        )
    io.open(CSS_PATH, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

    total = sum(os.path.getsize(os.path.join(OUT_DIR, f[1])) for f in faces)
    print("%d faces, %d bytes, css %d bytes" % (len(faces), total, os.path.getsize(CSS_PATH)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
